type testGenerator struct {
	body    bytes.Buffer
	imports map[string]bool
}

type testCase struct {
	args   []symbolic.SymbolicExpression
	result symbolic.SymbolicExpression
	panic  *PanicInfo
	blocks map[*ssa.BasicBlock]int
	length int
}

func minimize(cases []testCase) []testCase {
	covered := make(map[*ssa.BasicBlock]bool)
	var selected []testCase
	for {
		best, bestGain := -1, 0
		for i, c := range cases {
			gain := 0
			for block := range c.blocks {
				if !covered[block] {
					gain++
				}
			}
			if gain > bestGain || gain > 0 && gain == bestGain && c.length < cases[best].length {
				best, bestGain = i, gain
			}
		}
		if best < 0 {
			break
		}
		for block := range cases[best].blocks {
			covered[block] = true
		}
		selected = append(selected, cases[best])
	}
	return selected
}

func collectCases(source, name string) []testCase {
	var cases []testCase
	for _, state := range Analyse(source, name) {
		args, result, ok := state.Analyser.Concretize(state)
		if !ok {
			continue
		}
		blocks := state.CallStack[0].BlockVisits
		length := 0
		for _, visits := range blocks {
			length += visits
		}
		cases = append(cases, testCase{
			args:   args,
			result: result,
			panic:  state.Panic,
			blocks: blocks,
			length: length,
		})
	}
	return minimize(cases)
}

func (gen *testGenerator) function(source string, fn *ast.FuncDecl) {
	name := fn.Name.Name
	cases := collectCases(source, name)

	var params []string
	for _, field := range fn.Type.Params.List {
		for _, paramName := range field.Names {
			params = append(params, paramName.Name)
		}
	}

	fmt.Fprintf(&gen.body, "func Test_%s(t *testing.T) {\n", name)
	for _, c := range cases {
		gen.testCase(name, params, c)
	}
	gen.body.WriteString("}\n\n")
}

func (gen *testGenerator) testCase(function string, params []string, c testCase) {
	args := make([]string, len(c.args))
	labels := make([]string, len(c.args))
	for i, arg := range c.args {
		args[i] = gen.literal(arg)
		labels[i] = params[i] + "=" + arg.String()
	}
	call := fmt.Sprintf("%s(%s)", function, strings.Join(args, ", "))

	fmt.Fprintf(&gen.body, "t.Run(%q, func(t *testing.T) {\n", strings.Join(labels, ","))
	switch {
	case c.panic != nil:
		gen.expectPanic(c.panic.Message)
		fmt.Fprintf(&gen.body, "%s\n", call)
	case c.result == nil:
		fmt.Fprintf(&gen.body, "%s\n", call)
	default:
		gen.expectResult(call, c.result)
	}
	gen.body.WriteString("})\n")
}

func (gen *testGenerator) expectPanic(message string) {
	gen.body.WriteString("defer func() {\nr := recover()\n")
	gen.body.WriteString("if r == nil {\nt.Fatal(\"expected panic\")\n}\n")
	if message != "" {
		gen.imports["fmt"] = true
		gen.imports["strings"] = true
		fmt.Fprintf(&gen.body, "if !strings.Contains(fmt.Sprint(r), %q) {\n", message)
		fmt.Fprintf(&gen.body, "t.Fatalf(\"expected panic %%q, got %%v\", %q, r)\n}\n", message)
	}
	gen.body.WriteString("}()\n")
}

func (gen *testGenerator) expectResult(call string, result symbolic.SymbolicExpression) {
	if f, ok := result.(*symbolic.FloatConstant); ok && math.IsNaN(f.Value) {
		fmt.Fprintf(&gen.body, "if got := %s; got == got {\n", call)
		gen.body.WriteString("t.Errorf(\"got %v, want NaN\", got)\n}\n")
		return
	}
	want := gen.literal(result)
	fmt.Fprintf(&gen.body, "if got := %s; got != %s {\n", call, want)
	fmt.Fprintf(&gen.body, "t.Errorf(\"got %%v, want %%v\", got, %s)\n}\n", want)
}

func (gen *testGenerator) literal(value symbolic.SymbolicExpression) string {
	switch value := value.(type) {
	case *symbolic.IntConstant:
		return strconv.FormatInt(value.Value, 10)
	case *symbolic.BoolConstant:
		return strconv.FormatBool(value.Value)
	case *symbolic.FloatConstant:
		switch v := value.Value; {
		case math.IsNaN(v):
			gen.imports["math"] = true
			return "math.NaN()"
		case math.IsInf(v, 0):
			gen.imports["math"] = true
			return fmt.Sprintf("math.Inf(%d)", int(math.Copysign(1, v)))
		case v == 0 && math.Signbit(v):
			gen.imports["math"] = true
			return "math.Copysign(0, -1)"
		default:
			return strconv.FormatFloat(v, 'g', -1, 64)
		}
	}
	panic(fmt.Sprintf("unsupported test value %s of type %s", value, value.Type()))
}

func (gen *testGenerator) file(pkg string) []byte {
	var out bytes.Buffer
	out.WriteString("// Code generated by symbolic-execution-course test generator. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\nimport (\n", pkg)
	for _, path := range slices.Sorted(maps.Keys(gen.imports)) {
		fmt.Fprintf(&out, "%q\n", path)
	}
	out.WriteString(")\n\n")
	out.Write(gen.body.Bytes())
	return out.Bytes()
}

func GenerateTestFile(sourceFile string) string {
	source, err := os.ReadFile(sourceFile)
	if err != nil {
		panic(err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), sourceFile, source, 0)
	if err != nil {
		panic(err)
	}

	gen := &testGenerator{imports: map[string]bool{"testing": true}}
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok {
			gen.function(string(source), fn)
		}
	}

	formatted, err := format.Source(gen.file(file.Name.Name))
	if err != nil {
		panic(err)
	}
	testFile := strings.TrimSuffix(sourceFile, ".go") + "_test.go"
	if err := os.WriteFile(testFile, formatted, 0o644); err != nil {
		panic(err)
	}
	return testFile
}
